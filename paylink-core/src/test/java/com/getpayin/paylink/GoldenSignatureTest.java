package com.getpayin.paylink;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.getpayin.paylink.internal.EndpointSpec;
import com.getpayin.paylink.internal.FieldOrders;
import com.getpayin.paylink.internal.PaylinkConfig;
import com.getpayin.paylink.internal.Signature;
import com.getpayin.paylink.internal.SignedBody;
import com.getpayin.paylink.webhook.DefaultWebhooks;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import com.google.gson.JsonPrimitive;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.time.Duration;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import org.junit.jupiter.api.Test;

/**
 * Cross-language signature parity. Reuses the JS/Python/PHP golden-signature fixtures
 * (generated by PHP with the same primitive the server uses). If these pass, the Java SDK
 * builds byte-identical signatures to the server and the other SDKs.
 */
class GoldenSignatureTest {

    private static final Map<String, EndpointSpec> SPECS = Map.ofEntries(
            Map.entry("INVOICE_CREATE", FieldOrders.INVOICE_CREATE),
            Map.entry("PAYMENT_VOID", FieldOrders.PAYMENT_VOID),
            Map.entry("PAYMENT_REFUND", FieldOrders.PAYMENT_REFUND),
            Map.entry("PAYMENT_SETTLE", FieldOrders.PAYMENT_SETTLE),
            Map.entry("PAYMENT_REVERSE_AUTHORIZATION", FieldOrders.PAYMENT_REVERSE_AUTHORIZATION),
            Map.entry("PAYMENT_CHECK_STATUS", FieldOrders.PAYMENT_CHECK_STATUS),
            Map.entry("VCC_CHARGE", FieldOrders.VCC_CHARGE),
            Map.entry("CARD_TOKENIZE", FieldOrders.CARD_TOKENIZE),
            Map.entry("CARD_CHARGE", FieldOrders.CARD_CHARGE),
            Map.entry("CARD_REVOKE", FieldOrders.CARD_REVOKE),
            Map.entry("RECURRING_CREATE", FieldOrders.RECURRING_CREATE));

    private final JsonObject fixtures = loadFixtures();

    @Test
    void primitiveSignatureMatchesEveryCase() {
        for (JsonElement element : fixtures.getAsJsonArray("cases")) {
            JsonObject testCase = element.getAsJsonObject();
            List<String> values = new ArrayList<>();
            for (JsonElement value : testCase.getAsJsonArray("values")) {
                values.add(value.getAsString());
            }
            assertEquals(testCase.get("expected").getAsString(), Signature.build(values, hashToken(testCase)),
                    "primitive: " + testCase.get("name").getAsString());
        }
    }

    @Test
    void structuredBodySignatureMatches() {
        for (JsonElement element : fixtures.getAsJsonArray("cases")) {
            JsonObject testCase = element.getAsJsonObject();
            EndpointSpec spec = SPECS.get(testCase.get("endpoint").getAsString());
            if (spec == null) {
                continue;
            }
            Map<String, Object> input = snakeInput(testCase.getAsJsonObject("input"));
            Map<String, String> body = SignedBody.build(spec, input, "pub_token", hashToken(testCase));
            assertEquals(testCase.get("expected").getAsString(), body.get("signature"),
                    "structured: " + testCase.get("name").getAsString());
            assertEquals("pub_token", body.get("token"));
        }
    }

    @Test
    void mandateActionSignsTheUid() {
        JsonObject testCase = findCase("RECURRING_MANDATE_ACTION");
        String uid = testCase.getAsJsonObject("input").get("mandateId").getAsString();
        assertEquals(testCase.get("expected").getAsString(), Signature.build(List.of(uid), hashToken(testCase)));
    }

    @Test
    void webhookSignatureVerifies() {
        for (JsonElement element : fixtures.getAsJsonArray("cases")) {
            JsonObject testCase = element.getAsJsonObject();
            if (!"WEBHOOK".equals(testCase.get("endpoint").getAsString())) {
                continue;
            }
            String hash = hashToken(testCase);
            DefaultWebhooks webhooks = new DefaultWebhooks(webhookConfig(hash));

            JsonObject payload = testCase.getAsJsonObject("input").deepCopy();
            payload.addProperty("signature", testCase.get("expected").getAsString());
            assertTrue(webhooks.isValid(payload.toString()), "webhook: " + testCase.get("name").getAsString());

            JsonObject tampered = payload.deepCopy();
            tampered.addProperty("signature", "AAAA");
            assertFalse(webhooks.isValid(tampered.toString()));
        }
    }

    private static PaylinkConfig webhookConfig(String hashToken) {
        return new PaylinkConfig("pub", hashToken, "https://pay.getpayin.com",
                Duration.ofSeconds(30), 2, null, Duration.ofMillis(250), null, null);
    }

    private static Map<String, Object> snakeInput(JsonObject input) {
        Map<String, Object> result = new LinkedHashMap<>();
        for (Map.Entry<String, JsonElement> entry : input.entrySet()) {
            result.put(toSnake(entry.getKey()), toValue(entry.getValue()));
        }
        return result;
    }

    private static Object toValue(JsonElement element) {
        if (element.isJsonNull() || !element.isJsonPrimitive()) {
            return null;
        }
        JsonPrimitive primitive = element.getAsJsonPrimitive();
        if (primitive.isString()) {
            return primitive.getAsString();
        }
        if (primitive.isBoolean()) {
            return primitive.getAsBoolean();
        }
        return primitive.getAsString().contains(".")
                ? (Object) primitive.getAsDouble()
                : (Object) primitive.getAsLong();
    }

    private static String toSnake(String camel) {
        StringBuilder builder = new StringBuilder();
        for (char character : camel.toCharArray()) {
            if (Character.isUpperCase(character)) {
                builder.append('_').append(Character.toLowerCase(character));
            } else {
                builder.append(character);
            }
        }
        return builder.toString();
    }

    private static String hashToken(JsonObject testCase) {
        return testCase.has("hashToken") ? testCase.get("hashToken").getAsString() : "test_hash_token_abc123";
    }

    private JsonObject findCase(String endpoint) {
        for (JsonElement element : fixtures.getAsJsonArray("cases")) {
            JsonObject testCase = element.getAsJsonObject();
            if (endpoint.equals(testCase.get("endpoint").getAsString())) {
                return testCase;
            }
        }
        throw new IllegalStateException("Missing fixture: " + endpoint);
    }

    private JsonObject loadFixtures() {
        try (InputStream stream = getClass().getResourceAsStream("/golden-signatures.json")) {
            String text = new String(stream.readAllBytes(), StandardCharsets.UTF_8);
            return JsonParser.parseString(text).getAsJsonObject();
        } catch (Exception e) {
            throw new IllegalStateException("Could not load golden-signatures.json", e);
        }
    }
}
